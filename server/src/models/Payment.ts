import mongoose, { Schema } from 'mongoose';
import { IPayment } from '../types/index.js';

const receiptSchema = new Schema(
  {
    number: { type: String, required: true },
    generatedAt: { type: Date, required: true },
    url: { type: String },
  },
  { _id: false }
);

const paymentSchema = new Schema<IPayment>(
  {
    tenantId: {
      type: Schema.Types.ObjectId,
      ref: 'Tenant',
      required: true,
      index: true,
    },
    unitId: {
      type: Schema.Types.ObjectId,
      ref: 'Unit',
      required: true,
    },
    propertyId: {
      type: Schema.Types.ObjectId,
      ref: 'Property',
      required: true,
      index: true,
    },
    ownerId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    amount: {
      type: Number,
      required: true,
    },
    type: {
      type: String,
      enum: ['rent', 'deposit', 'maintenance', 'utility', 'penalty', 'custom'],
      required: true,
    },
    // Schedule reference (for auto-generated payments)
    scheduleId: {
      type: Schema.Types.ObjectId,
      ref: 'PaymentSchedule',
      index: true,
    },
    isAutoGenerated: {
      type: Boolean,
      default: false,
    },
    remindersSent: [
      {
        type: {
          type: String,
          enum: ['due', 'overdue', 'upcoming'],
          required: true,
        },
        sentAt: {
          type: Date,
          required: true,
        },
        daysBeforeDue: {
          type: Number,
          required: true,
        },
      },
    ],
    status: {
      type: String,
      enum: ['pending', 'completed', 'failed', 'refunded'],
      default: 'pending',
    },
    paymentMethod: {
      type: String,
      enum: ['chapa', 'telebirr', 'santimpay', 'manual', 'bank_transfer'],
      default: 'chapa',
    },
    // Generic gateway fields (new)
    gatewayReference: {
      type: String,
      index: true,
    },
    gatewayTransactionRef: {
      type: String,
      index: true,
      sparse: true,
    },
    gatewayMetadata: {
      type: Schema.Types.Mixed,
    },
    // Legacy Chapa fields (for backward compatibility)
    chapaReference: {
      type: String,
      index: true,
    },
    chapaTxRef: {
      type: String,
      unique: true,
      sparse: true,
    },
    dueDate: {
      type: Date,
      required: true,
    },
    paidAt: {
      type: Date,
    },
    month: {
      type: Number,
      required: true,
      min: 1,
      max: 12,
    },
    year: {
      type: Number,
      required: true,
    },
    receipt: {
      type: receiptSchema,
    },
    // Bank transfer fields
    bankTransferReceipt: {
      type: String,
    },
    bankTransferApprovalStatus: {
      type: String,
      enum: ['pending_approval', 'approved', 'rejected'],
    },
    bankTransferApprovalNotes: {
      type: String,
    },
    approvedBy: {
      type: Schema.Types.ObjectId,
      ref: 'User',
    },
    approvedAt: {
      type: Date,
    },
  },
  {
    timestamps: true,
  }
);

// Index for finding payments by month/year
paymentSchema.index({ tenantId: 1, month: 1, year: 1 });
paymentSchema.index({ ownerId: 1, status: 1 });

// Index for finding payments by gateway and transaction reference
paymentSchema.index({ paymentMethod: 1, gatewayTransactionRef: 1 });

// Index for bank transfer approval status
paymentSchema.index({ ownerId: 1, bankTransferApprovalStatus: 1 });

// Unique index for auto-generated payments to prevent duplicates
paymentSchema.index({ scheduleId: 1, month: 1, year: 1 }, { unique: true, sparse: true });

// Static method to generate receipt number
paymentSchema.statics.generateReceiptNumber = function (): string {
  const timestamp = Date.now();
  const random = Math.random().toString(36).substring(2, 6).toUpperCase();
  return `RCP-${timestamp}-${random}`;
};

const Payment = mongoose.model<IPayment>('Payment', paymentSchema);

export default Payment;
